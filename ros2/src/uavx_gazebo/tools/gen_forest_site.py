#!/usr/bin/env python3
"""Import the GC1 scenery and generate its planner map from an organiser checkout.

    python3 tools/gen_forest_site.py --uavsim ~/src/uavsim

The upstream renderer supplies the static scene. UAV-X spawns its own vehicles and
mission targets. Running the generator requires PyYAML, Jinja2 and jsonschema.
"""
from __future__ import annotations

import argparse
import math
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent

# ----------------------------------------------------------------- organisers' GCS site
# uavsim/site.py SiteLayout() defaults, and DEFAULT_GCS_POSE.
SITE_POSE = (-365.0, 0.0, 0.0)
PAD_ROWS, PAD_COLS = 4, 6
PAD_SPACING_M = 6.0
PAD_RADIUS_M = 1.6
APRON_MARGIN_M = 3.0
APRON_LENGTH_M = PAD_ROWS * PAD_SPACING_M + 2 * APRON_MARGIN_M      # 30 m, along +x (at the ROI)
APRON_WIDTH_M = PAD_COLS * PAD_SPACING_M + 2 * APRON_MARGIN_M       # 42 m
FRONT_X_M = APRON_LENGTH_M / 2.0                                    # 15 m, site frame
SHELTER_Y_M = -(PAD_COLS * PAD_SPACING_M / 2) - 8                   # -26 m, site frame
MAST_HEIGHT_M = 10.0
# uavsim world.py DEFAULT_ORIGIN: the CMAC origin its ArduPilot parameter files assume.
ORIGIN = {"latitude_deg": -35.389138, "longitude_deg": 149.219188, "elevation_m": 580.0}

# ----------------------------------------------------------------- organisers' ROI
MISSION_EXTENT = (-250.0, 250.0, -250.0, 250.0)
SPECIES = {                      # from the ROI collision cylinders
    "oak": {"radius_m": 5.0, "height_m": 6.5, "trunk_r_m": 0.45, "color": [0.17, 0.36, 0.15], "count": 436},
    "pine": {"radius_m": 1.6, "height_m": 5.1, "trunk_r_m": 0.30, "color": [0.13, 0.30, 0.18], "count": 290},
}
CANOPY_LOSS_DB_PER_M = 0.4       # leafy canopy at a few GHz (ITU-R P.833 order of magnitude)
CANOPY_MAX_LOSS_DB = 25.0


def site_to_world(x: float, y: float) -> tuple[float, float]:
    return SITE_POSE[0] + x, SITE_POSE[1] + y


def pad_slots() -> list[tuple[float, float]]:
    """Pad centres in world coordinates, the row nearest the forest first, left to right."""
    out = []
    for row in range(PAD_ROWS):
        for col in range(PAD_COLS):
            x = (PAD_ROWS - 1 - row) * PAD_SPACING_M - (PAD_ROWS - 1) * PAD_SPACING_M / 2.0
            y = (col - (PAD_COLS - 1) / 2.0) * PAD_SPACING_M
            out.append(site_to_world(x, y))
    return out


def read_trees(uavsim: Path) -> list[tuple[float, float, int]]:
    """(x, y, species_index) for every trunk, in the organisers' SDF order: oaks then pines."""
    sdf = uavsim / "worlds" / "fragments" / "roi_forest.sdf"
    if sdf.is_file():
        text = sdf.read_text(encoding="utf-8")
        found = re.findall(r'<collision name="(Oak|Pine)_Tree_\d+_collision">\s*<pose>([^<]*)</pose>', text)
        trees = []
        for species, pose in found:
            x, y = pose.split()[:2]
            trees.append((round(float(x), 2), round(float(y), 2), 0 if species == "Oak" else 1))
        if trees:
            return trees
    meta = uavsim / "worlds" / "fragments" / "roi_forest.yaml"
    if not meta.is_file():
        raise SystemExit(f"neither {sdf} nor {meta} found - pass --uavsim <clone of the organisers' uavsim>")
    import yaml
    data = yaml.safe_load(meta.read_text(encoding="utf-8")) or {}
    oaks = SPECIES["oak"]["count"]
    return [(round(float(t[0]), 2), round(float(t[1]), 2), 0 if i < oaks else 1)
            for i, t in enumerate(data.get("trees") or [])]


# ----------------------------------------------------------------------------- map file
def write_map(trees, path: Path) -> None:
    pads = pad_slots()
    mast_x, mast_y = site_to_world(6.0, SHELTER_Y_M)
    shelter_x, shelter_y = site_to_world(0.0, SHELTER_Y_M)
    apron_x, apron_y = site_to_world(0.0, 0.0)
    x0, x1, y0, y1 = MISSION_EXTENT
    lines = [
        "# forest_rescue - the PUSHPAK Grand Challenge 1 forest search site.",
        "#",
        "# GENERATED by uavx_gazebo/tools/gen_forest_site.py from the organisers' simulation",
        "# environment (uavsim: worlds/fragments/roi_forest.* and uavsim/site.py). Do not edit by",
        "# hand - re-run the generator. Every number below is the organisers'.",
        "#",
        "# Frame: world ENU metres, origin at the CENTRE of the 500 m x 500 m search area (the",
        "# organisers' geographic origin), so the GCS sits at x = -365 and the forest spans",
        "# x, y in [-250, 250]. Heights are above ground.",
        "#",
        "#   apron rear    -380      pad rows -374 .. -356      apron front -350",
        "#   ............. 100 m of open ground .............",
        "#   forest edge   -250      forest centre 0            forest edge  +250",
        "#",
        "# The geometry that follows drives the Gazebo world, the companions' path planning, the",
        "# radio channel (canopy and mast shadowing), the coverage planner and the referee.",
        "name: forest_rescue",
        "description: >",
        "  The organisers' forest search site: a 500 m x 500 m wooded search area centred on the",
        f"  world origin ({len(trees)} trees, perimeter posts every 20 m), with the ground control",
        "  station 365 m west of it - its apron edge 100 m short of the tree line.",
        "scenery_world: uavx_forest.sdf",
        "planner_cell_m: 6.0",
        "",
        "# Geographic origin of the organisers' world (uavsim world.py DEFAULT_ORIGIN).",
        "frame:",
        "  origin: roi_centre",
        f"  latitude_deg: {ORIGIN['latitude_deg']}",
        f"  longitude_deg: {ORIGIN['longitude_deg']}",
        f"  elevation_m: {ORIGIN['elevation_m']}",
        "",
        "# The area to be surveyed: 500 m x 500 m (organisers' Q6).",
        "mission_area:",
        f"  x: [{x0}, {x1}]",
        f"  y: [{y0}, {y1}]",
        "",
        "# Flight envelope the referee enforces: the search area, the transit corridor and the",
        "# GCS apron, plus margin; 100 m ceiling as in uavx_quad.parm (FENCE_ALT_MAX).",
        "geofence:",
        "  x: [-420.0, 300.0]",
        "  y: [-300.0, 300.0]",
        "  z_max: 100.0",
        "",
        "gcs:",
        "  # The antenna is on the mast beside the shelter, not at the apron centre.",
        f"  antenna_m: [{round(mast_x, 1)}, {round(mast_y, 1)}, {MAST_HEIGHT_M}]",
        "  apron:",
        f"    center: [{round(apron_x, 1)}, {round(apron_y, 1)}]",
        f"    size: [{APRON_LENGTH_M}, {APRON_WIDTH_M}]",
        f"    pad_radius_m: {PAD_RADIUS_M}",
        f"  # {len(pads)} pads, 4 rows x 6 columns {PAD_SPACING_M:.0f} m apart; the row nearest the forest first.",
        "  pads:",
    ]
    lines += [f"    - [{round(x, 1)}, {round(y, 1)}]" for x, y in pads]
    lines += [
        "",
        "# Structures at the ground station: obstacles for the planner and the referee, and the",
        "# mast shadows the radio for a UAV low on the far side of it.",
        "obstacles:",
        f"  - {{id: GCS_SHELTER, kind: shelter, center: [{round(shelter_x, 1)}, {round(shelter_y, 1)}],"
        " size: [8, 4, 3], attenuation_db: 8, color: [0.85, 0.85, 0.80]}",
        f"  - {{id: GCS_MAST, kind: mast, shape: cylinder, center: [{round(mast_x, 1)}, {round(mast_y, 1)}],"
        f" radius: 0.12, height: {MAST_HEIGHT_M}, attenuation_db: 3, color: [0.7, 0.12, 0.12]}}",
        "",
        "# The forest. Trees are a canopy layer rather than individual obstacles: at survey height",
        "# they are nothing to fly round, but a radio path that dips into the crowns loses signal,",
        "# and the referee still has to see a UAV that descends into one.",
        "canopy:",
        f"  top_m: {max(s['height_m'] for s in SPECIES.values())}",
        f"  loss_db_per_m: {CANOPY_LOSS_DB_PER_M}",
        f"  max_loss_db: {CANOPY_MAX_LOSS_DB}",
        "  species:",
    ]
    for name, s in SPECIES.items():
        lines.append(f"    {name}: {{radius_m: {s['radius_m']}, height_m: {s['height_m']}, "
                     f"trunk_r_m: {s['trunk_r_m']}, color: {s['color']}}}")
    lines += [
        f"  # {len(trees)} trunks: [x, y, species] with species 0 = oak, 1 = pine (organisers' order).",
        "  trees:",
    ]
    lines += [f"    - [{x}, {y}, {s}]" for x, y, s in trees]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- world file
def write_world(uavsim: Path, path: Path) -> None:
    sys.path.insert(0, str(uavsim.resolve()))
    from uavsim.world import WorldSpec, build

    # Upstream provides the complete static site. The mission manager places PoIs
    # during flight, so the upstream renderer gets its default empty target list.
    with tempfile.TemporaryDirectory() as temp:
        built = build(WorldSpec(name="uavx_forest"), Path(temp))
        text = built.info.sdf_path.read_text(encoding="utf-8")

    # Resolve the same versioned Fuel resources from the installed Gazebo package.
    for species, version in (("oak", 7), ("pine", 6)):
        fuel = f"https://fuel.gazebosim.org/1.0/openrobotics/models/{species} tree/{version}/files/"
        text = text.replace(fuel, f"model://{species}_tree/")
    # Additional sensor systems used by the UAV-X vehicle.
    anchor = '    <plugin filename="gz-sim-imu-system"'
    text = text.replace(anchor,
                        '    <plugin filename="gz-sim-air-speed-system" name="gz::sim::systems::AirSpeed"/>\n'
                        '    <plugin filename="gz-sim-altimeter-system" name="gz::sim::systems::Altimeter"/>\n'
                        + anchor, 1)
    path.write_text(text, encoding="utf-8", newline="\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--uavsim", type=Path, default=Path(os.environ.get("UAVSIM_DIR", "~/src/uavsim")).expanduser(),
                    help="clone of the organisers' uavsim repository (holds worlds/fragments/roi_forest.*)")
    ap.add_argument("--map-out", type=Path, default=PKG / "maps" / "forest_rescue.yaml")
    ap.add_argument("--world-out", type=Path, default=PKG / "worlds" / "uavx_forest.sdf")
    args = ap.parse_args(argv)

    trees = read_trees(args.uavsim.expanduser())
    oaks = sum(1 for t in trees if t[2] == 0)
    args.map_out.parent.mkdir(parents=True, exist_ok=True)
    args.world_out.parent.mkdir(parents=True, exist_ok=True)
    write_map(trees, args.map_out)
    write_world(args.uavsim.expanduser(), args.world_out)
    corner = math.hypot(MISSION_EXTENT[1] - SITE_POSE[0], MISSION_EXTENT[3])
    print(f"{args.map_out}: {len(trees)} trees ({oaks} oak, {len(trees) - oaks} pine), "
          f"{PAD_ROWS * PAD_COLS} pads")
    print(f"{args.world_out}: imported Gazebo scenery")
    print(f"GCS mast to the far corner of the search area: {corner:.0f} m "
          f"(at a 100 m radio range, {math.ceil(corner / 90.0) - 1} relays for a live link)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
